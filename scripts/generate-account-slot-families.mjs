#!/usr/bin/env node
// Regenerates packages/core/agents/account-slot-families.ts from
// server/pkg/agent/account_slot_families.json (the single source of truth).
//
// Run via `pnpm generate:account-slot-families`. CI re-runs the generator and
// `git diff --exit-code`s the output, so the JSON and TS sides cannot drift.

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const jsonPath = resolve(repoRoot, "server/pkg/agent/account_slot_families.json");
const tsPath = resolve(repoRoot, "packages/core/agents/account-slot-families.ts");

const data = JSON.parse(readFileSync(jsonPath, "utf8"));
const label = "account_slot_families.json";

if (!Number.isInteger(data.max_account_number) || data.max_account_number < 1) {
  throw new Error(`${label}: "max_account_number" must be a positive integer`);
}
if (!Array.isArray(data.families) || data.families.length === 0) {
  throw new Error(`${label}: expected a non-empty "families" array`);
}

const STRING_FIELDS = [
  "cli",
  "base_dir",
  "account_dir_prefix",
  "lever",
  "runtime_config_key",
];

const seenCli = new Set();
const seenKey = new Set();
for (const family of data.families) {
  for (const field of STRING_FIELDS) {
    if (typeof family[field] !== "string" || family[field].length === 0) {
      throw new Error(`${label}: family ${JSON.stringify(family.cli)} needs a non-empty "${field}"`);
    }
  }
  if (
    !Array.isArray(family.default_accounts) ||
    family.default_accounts[0] !== 1 ||
    !family.default_accounts.every((n) => Number.isInteger(n) && n >= 1 && n <= data.max_account_number)
  ) {
    throw new Error(`${label}: family ${family.cli} "default_accounts" must be slot numbers starting with 1`);
  }
  if (typeof family.rotates_on_quota !== "boolean") {
    throw new Error(`${label}: family ${family.cli} needs a boolean "rotates_on_quota"`);
  }
  if (seenCli.has(family.cli)) throw new Error(`${label}: duplicate cli ${family.cli}`);
  if (seenKey.has(family.runtime_config_key)) {
    throw new Error(`${label}: duplicate runtime_config_key ${family.runtime_config_key}`);
  }
  seenCli.add(family.cli);
  seenKey.add(family.runtime_config_key);
}

const lines = [];
lines.push("// AUTO-GENERATED by scripts/generate-account-slot-families.mjs.");
lines.push("// Do not edit by hand — edit server/pkg/agent/account_slot_families.json");
lines.push("// and run `pnpm generate:account-slot-families`.");
lines.push("");
lines.push("/**");
lines.push(" * One CLI family that owns a numbered account-slot registry: slot 1 is the");
lines.push(" * CLI's own directory (`baseDir`), slot N is `<accountDirPrefix>N`, and an");
lines.push(" * agent's registered slots live under `runtime_config[runtimeConfigKey]` as");
lines.push(" * `{ accounts: number[] }`.");
lines.push(" *");
lines.push(" * Single source of truth: `server/pkg/agent/account_slot_families.json`. The");
lines.push(" * Go daemon embeds that JSON for its account probe; this file is regenerated");
lines.push(" * from it. A CLI absent from this table (codex, cursor) cannot be rebound by");
lines.push(" * the daemon and therefore has no slots to register.");
lines.push(" */");
lines.push("export type AccountSlotFamily = {");
lines.push("  readonly cli: string;");
lines.push("  readonly baseDir: string;");
lines.push("  readonly accountDirPrefix: string;");
lines.push("  /** `custom_args:<flag>` or `env:<KEY>` — how a bound slot reaches the CLI. */");
lines.push("  readonly lever: string;");
lines.push("  readonly runtimeConfigKey: string;");
lines.push("  /** Seeds the list for an agent that never saved one. Always starts with 1. */");
lines.push("  readonly defaultAccounts: readonly number[];");
lines.push("  /**");
lines.push("   * True only where the daemon detects an exhausted quota and moves to the");
lines.push("   * next slot. Every other family's slots are a manual registry.");
lines.push("   */");
lines.push("  readonly rotatesOnQuota: boolean;");
lines.push("};");
lines.push("");
lines.push(`export const MAX_ACCOUNT_SLOT_NUMBER = ${data.max_account_number};`);
lines.push("");
lines.push("export const ACCOUNT_SLOT_FAMILIES: readonly AccountSlotFamily[] = [");
for (const family of data.families) {
  lines.push("  {");
  lines.push(`    cli: ${JSON.stringify(family.cli)},`);
  lines.push(`    baseDir: ${JSON.stringify(family.base_dir)},`);
  lines.push(`    accountDirPrefix: ${JSON.stringify(family.account_dir_prefix)},`);
  lines.push(`    lever: ${JSON.stringify(family.lever)},`);
  lines.push(`    runtimeConfigKey: ${JSON.stringify(family.runtime_config_key)},`);
  lines.push(`    defaultAccounts: [${family.default_accounts.join(", ")}],`);
  lines.push(`    rotatesOnQuota: ${family.rotates_on_quota},`);
  lines.push("  },");
}
lines.push("];");
lines.push("");
lines.push("export function accountSlotFamily(cli: string): AccountSlotFamily | null {");
lines.push("  return ACCOUNT_SLOT_FAMILIES.find((family) => family.cli === cli) ?? null;");
lines.push("}");
lines.push("");

writeFileSync(tsPath, lines.join("\n"));
