package main

import (
	"encoding/json"
	"fmt"
	"io"
	"os"
	"strconv"

	"github.com/multica-ai/multica/server/internal/cli"
	"github.com/spf13/cobra"
)

func init() {
	reminder := &cobra.Command{Use: "reminder", Short: "Deliver server-decided owner reminders (human owner/admin only)", Long: `Transport-only outbox. The server judges deliveries, blocks and stalls and
deduplicates them.
Normal agents cannot claim this queue. Use the installed Mac delivery worker
with its saved owner profile. This command never reruns or hands off an issue.
A claim token is a durable UUID generated by the worker; repeat it after a lost
response. Claims never expire into an automatic replay. Receipt results:
sent = accepted; not_sent = proven pre-send failure (at most one retry);
uncertain = delivery may have happened (terminal, never automatically replayed);
stale = the worker's last read found the issue had moved on (terminal, not sent).`}
	for _, verb := range []string{"claim", "receipt"} {
		verb := verb
		use := verb
		args := cobra.NoArgs
		if verb == "receipt" {
			use += " <reminder-id>"
			args = exactArgs(1)
		}
		cmd := &cobra.Command{Use: use, Short: map[string]string{"claim": "Claim up to 50 reminders with a durable request token", "receipt": "Record delivery result for a claimed reminder"}[verb], Args: args, RunE: func(cmd *cobra.Command, args []string) error { return runIssueReminder(cmd, args, verb) }}
		cmd.Annotations = map[string]string{annotationAccess: "write", annotationBotKey: "no"}
		cmd.Flags().String("content-file", "", "JSON body file: claim_token, plus result for receipt")
		cmd.Flags().Bool("content-stdin", false, "Read JSON body from stdin")
		cmd.Flags().String("output", "json", "Output format: json")
		reminder.AddCommand(cmd)
	}
	issueCmd.AddCommand(reminder)
}

func runIssueReminder(cmd *cobra.Command, args []string, verb string) error {
	output, _ := cmd.Flags().GetString("output")
	if output != "json" {
		return fmt.Errorf("--output must be json")
	}
	file, _ := cmd.Flags().GetString("content-file")
	stdin, _ := cmd.Flags().GetBool("content-stdin")
	if (file != "") == stdin {
		return fmt.Errorf("provide exactly one of --content-file or --content-stdin")
	}
	var reader io.Reader = cmd.InOrStdin()
	if file != "" {
		f, err := os.Open(file)
		if err != nil {
			return err
		}
		defer f.Close()
		reader = f
	}
	var body map[string]any
	data, err := io.ReadAll(io.LimitReader(reader, 1025))
	if err != nil || len(data) > 1024 || json.Unmarshal(data, &body) != nil {
		return fmt.Errorf("expected JSON body at most 1 KiB")
	}
	client, ws, ctx, cancel, err := botClient(cmd)
	if err != nil {
		return err
	}
	defer cancel()
	path := "/api/workspaces/" + ws + "/issue-reminders/claim"
	if verb == "receipt" {
		id, err := strconv.ParseInt(args[0], 10, 64)
		if err != nil || id < 1 {
			return fmt.Errorf("reminder-id must be a positive integer")
		}
		path = "/api/workspaces/" + ws + "/issue-reminders/" + args[0] + "/receipt"
	}
	var response map[string]any
	if err = client.PostJSON(ctx, path, body, &response); err != nil {
		return err
	}
	return cli.PrintJSON(cmd.OutOrStdout(), response)
}
